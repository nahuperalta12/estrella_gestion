import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import vm from "node:vm";
import ts from "typescript";
const source=await readFile(new URL("../src/lib/conversions.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const context={exports:{}}; vm.runInNewContext(js,context);
const {fiberglassSegments,glueForFeathers,rodsForWeight,parseThousandths}=context.exports;
assert.equal(JSON.stringify(glueForFeathers("100","3","250")),JSON.stringify({grams:"300",pots:"1,2"}));
assert.equal(JSON.stringify(glueForFeathers("300","3","250")),JSON.stringify({grams:"900",pots:"3,6"}));
assert.equal(JSON.stringify(glueForFeathers("50","3","250")),JSON.stringify({grams:"150",pots:"0,6"}));
assert.equal(rodsForWeight("5","600"),"3000");
assert.equal(rodsForWeight("0.001","600"),"0");
assert.equal(rodsForWeight("0.005","600","2"),"2");
assert.equal(fiberglassSegments("1","3"),"3");
assert.equal(glueForFeathers("1.5","3","250"),null);
assert.equal(rodsForWeight("5","600","0"),null);
assert.equal(parseThousandths("1.0001"),null);
console.log("Pruebas de conversiones: correctas.");
